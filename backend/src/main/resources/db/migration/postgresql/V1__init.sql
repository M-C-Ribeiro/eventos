-- Multi-tenancy por coluna discriminadora: toda tabela de negócio tem tenant_id.

CREATE TABLE tenants (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(120) NOT NULL,
    slug        VARCHAR(60)  NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_tenants_slug UNIQUE (slug)
);

CREATE TABLE users (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id      BIGINT       NOT NULL REFERENCES tenants (id) ON DELETE CASCADE,
    name           VARCHAR(120) NOT NULL,
    email          VARCHAR(160) NOT NULL,
    password_hash  VARCHAR(255) NOT NULL,
    role           VARCHAR(20)  NOT NULL,
    active         BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_users_tenant_email UNIQUE (tenant_id, email)
);

CREATE TABLE events (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     BIGINT        NOT NULL REFERENCES tenants (id) ON DELETE CASCADE,
    title         VARCHAR(160)  NOT NULL,
    description   VARCHAR(4000),
    location      VARCHAR(255),
    start_at      TIMESTAMP     NOT NULL,
    end_at        TIMESTAMP     NOT NULL,
    capacity      INTEGER,
    status        VARCHAR(20)   NOT NULL,
    organizer_id  BIGINT        NOT NULL REFERENCES users (id),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_events_tenant_start ON events (tenant_id, start_at);

CREATE TABLE registrations (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id      BIGINT       NOT NULL REFERENCES tenants (id) ON DELETE CASCADE,
    event_id       BIGINT       NOT NULL REFERENCES events (id) ON DELETE CASCADE,
    user_id        BIGINT       REFERENCES users (id) ON DELETE SET NULL,
    name           VARCHAR(120) NOT NULL,
    email          VARCHAR(160) NOT NULL,
    status         VARCHAR(20)  NOT NULL,
    registered_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    checked_in_at  TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_registrations_event_email UNIQUE (event_id, email)
);

CREATE INDEX idx_registrations_tenant_event ON registrations (tenant_id, event_id);
